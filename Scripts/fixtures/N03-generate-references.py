#!/usr/bin/env python3
"""Exact binary Float inputs; independent Decimal two-pass population references."""
import decimal, json, struct
from pathlib import Path
D=decimal.Decimal
decimal.getcontext().prec=200

def value(bits):
    exponent=(bits>>23)&255; significand=bits&0x7fffff
    return D(significand if exponent==0 else significand+(1<<23))*D(2)**(exponent-150 if exponent else -149)

def rounded_bits(x):
    estimate=struct.unpack('<I',struct.pack('<f',float(x)))[0]
    candidates=range(max(0,estimate-1),min(0x7f7fffff,estimate+1)+1)
    return min(candidates,key=lambda b:(abs(value(b)-x),b&1))

large=struct.unpack('<I',struct.pack('<f',1e18))[0]
cases={
 'maxRange':[0,0x7f7fffff,0x7effffff,0x7f7fffff,1],
 'neighboringOffset':[large]*11+[large+1]*6,
 'tinyRange':[1,2,3,7,32,1,2,3],
 'mixedExponents':[0,1,0x00800000,0x3f800000,0x5d800000,0x6f800000],
 'smallOutlier':[large]*31+[large+8],
 'normalBoundary':[0x007fffff,0x00800000,0x00800001]*7,
}
rows=[]
for name,bits in cases.items():
    vals=list(map(value,bits));mean=sum(vals)/D(len(vals));variance=sum((x-mean)**2 for x in vals)/D(len(vals));std=variance.sqrt()
    rows.append(dict(name=name,inputBits=bits,meanDecimal=str(mean),stdDecimal=str(std),meanBits=rounded_bits(mean),stdBits=rounded_bits(std)))
root=Path(__file__).resolve().parents[2]


def wrap_swift_lines(text):
    lines = []
    for line in text.splitlines():
        indent = ' ' * (len(line) - len(line.lstrip()) + 4)
        while len(line) > 200:
            split = line.rfind(',', 0, 175) + 1
            assert split > 0
            lines.append(line[:split])
            line = indent + line[split:].lstrip()
        lines.append(line)
    return '\n'.join(lines) + '\n'

(root/'Tests/ComprehensiveTests/N03MagnitudeFixtures.swift').write_text(wrap_swift_lines('// Generated by Scripts/fixtures/N03-generate-references.py; Decimal precision 200.\nlet n03MagnitudeFixtures: [(name: String, bits: [UInt32], mean: UInt32, deviation: UInt32)] = [\n'+''.join(f'    ("{r["name"]}", {r["inputBits"]}, {r["meanBits"]}, {r["stdBits"]}),\n' for r in rows)+']\n'))
(root/'Scripts/fixtures/N03-reference-provenance.json').write_text(json.dumps(rows,indent=2)+'\n')
