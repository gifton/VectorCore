#!/usr/bin/env python3
"""Integer IEEE binary32 -> binary16 round-to-nearest-even reference; no library code."""
from pathlib import Path
import struct

def raw(value):
    return struct.unpack('>I', struct.pack('>f', value))[0]

def rounded(integer, shift):
    quotient, remainder = divmod(integer, 1 << shift)
    half = 1 << (shift - 1)
    return quotient + (remainder > half or (remainder == half and quotient & 1))

def half(bits):
    sign, exponent, fraction = (bits >> 16) & 0x8000, (bits >> 23) & 255, bits & 0x7fffff
    if exponent == 255:
        return sign | 0x7c00 | (0x200 if fraction else 0)
    if exponent == 0:
        return sign
    power = exponent - 127
    if power > 15:
        return sign | 0x7c00
    if power < -25:
        return sign
    significand = 0x800000 | fraction
    if power < -14:
        return sign | rounded(significand, -power - 1)
    mantissa = rounded(significand, 13)
    if mantissa == 2048:
        power += 1
        mantissa = 1024
    return sign | ((power + 15) << 10) | (mantissa - 1024)

cases = []
for name, value in [('zero-tie', 2**-25), ('normal-tie', 2**-14 - 2**-25), ('overflow-tie', 65520)]:
    for offset, suffix in [(-1, 'down'), (0, 'tie'), (1, 'up')]:
        bits = raw(value) + offset
        for sign, prefix in [(0, 'positive'), (0x80000000, 'negative')]:
            cases.append((f'{prefix}-{name}-{suffix}', bits | sign))
for name, bits in [('tiny',raw(1e-12)), ('max-half',raw(65504)), ('above-max-half',raw(65505)),
                   ('least-half-subnormal',raw(2**-24)), ('least-half-normal',raw(2**-14)),
                   ('max-float',0x7f7fffff), ('least-float-normal',0x00800000), ('least-float-subnormal',1),
                   ('zero',0), ('infinity',0x7f800000), ('quiet-nan',0x7fc12345), ('signaling-nan',0x7f800001)]:
    cases += [('positive-'+name,bits),('negative-'+name,bits|0x80000000)]
lines = ['// Generated by Scripts/ci/tests/Q03GenerateOracle.py; integer rounding reference.',
         'struct Q03OracleRow: Sendable {', '    let name: String', '    let input: UInt32', '    let output: UInt16',
         '    let category: Int // 0 ordinary, 1 overflow, 2 underflow, 3 subnormal, 4 NaN', '}',
         'let q03Oracle: [Q03OracleRow] = [']
for name, bits in cases:
    output = half(bits)
    exponent, fraction = (bits >> 23) & 255, bits & 0x7fffff
    category = 4 if exponent == 255 and fraction else 0
    if exponent != 255:
        magnitude = output & 0x7fff
        category = 1 if magnitude == 0x7c00 else 2 if magnitude == 0 and bits & 0x7fffffff else 3 if 0 < magnitude < 0x400 else 0
    lines.append(f'    .init(name: "{name}", input: 0x{bits:08x}, output: 0x{output:04x}, category: {category}),')
lines.append(']')
path = Path(__file__).resolve().parents[3] / 'Tests/ComprehensiveTests/Q03FP16Oracle.swift'
path.write_text('\n'.join(lines) + '\n')
print(f'{len(cases)} independent rows -> {path}')
