#!/usr/bin/env python3
"""Independent version-1 bytes: explicit little-endian words and two CRC oracles."""
import argparse,struct,zlib
from pathlib import Path

def bit_crc(data):
    crc=0xffffffff
    for byte in data:
        crc ^= byte
        for _ in range(8):crc=(crc>>1) ^ (0xedb88320 if crc&1 else 0)
    return crc ^ 0xffffffff

def frame(words,flags=0):
    body=struct.pack('<IHIH',0x56454354,1,len(words),flags)+b''.join(struct.pack('<I',x) for x in words)
    assert bit_crc(body)==zlib.crc32(body)
    return body+struct.pack('<I',bit_crc(body))

def generate():
    assert bit_crc(b'123456789')==zlib.crc32(b'123456789')==0xcbf43926
    cases={'empty':[], 'ordinary':[0x3f800000,0xc0200000,0], 'special':[0,0x80000000,0x7f800000,0xff800000,0x7fc00001,0xffc12345,0x7f800001,0xff800123,1,0x80000001,0x00800000,0x80800000,0x7f7fffff,0xff7fffff,0x3f800000,0xc0200000]}
    lines=['// Generated by Scripts/ci/fixtures/B01_generate_goldens.py; no Core writer/CRC used.','import Foundation','enum B01Golden {']
    def declaration(name, scalar, values):
        if not values:
            return ['    static let '+name+': ['+scalar+'] = []']
        return ['    static let '+name+': ['+scalar+'] = ['] + [
            '        '+', '.join(values[i:i+12])+(',' if i+12 < len(values) else '')
            for i in range(0,len(values),12)] + ['    ]']
    for name,words in cases.items():
        lines += declaration(name+'Words','UInt32',[f'0x{x:08x}' for x in words])
        lines += declaration(name+'Frame','UInt8',[f'0x{x:02x}' for x in frame(words)])
    lines+=['}','']
    return '\n'.join(lines)

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path,default=Path('Tests/ComprehensiveTests/B01Golden.swift'));args=p.parse_args();expected=generate()
    if args.check:assert args.output.read_text()==expected,'Golden fixture differs from independent generation'
    else:args.output.write_text(expected)
    print('B01_GOLDENS_OK crc=cbf43926 frames=empty,ordinary,special')
